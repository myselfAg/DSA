package dsa.Strings;

public class PrettyPrinting {
    static void main() {
        float a = 123.123456f;
        System.out.printf("Formatted String: %.2f", a);

        System.out.printf("PI: %.3f", Math.PI);

        System.out.printf("My name is %s and I am %d years old", "Agneesh", 21);
    }
}
